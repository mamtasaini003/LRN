def load_burgers(
    n_train: Optional[int] = 1000,
    n_test: int = 200,
    batch_size: int = 32,
    test_batch_size: int = 32,
    train_resolution: int = 16,
    test_resolutions: list = [16],
    data_root: Optional[Union[str, Path]] = None,
    temporal_subsample: int = 1,
    spatial_subsample: int = 1,
    return_processor: bool = True,
    return_tuple_format: bool = True,
) -> Tuple[DataLoader, Dict[int, DataLoader], Optional[DefaultDataProcessor]]:
    """
    Load 1D Burgers equation dataset using NeuralOperator's loader.
    
    Args:
        n_train: Number of training samples
        n_test: Number of test samples
        batch_size: Training batch size
        test_batch_size: Test batch size
        train_resolution: Resolution (16 or 128 available)
        test_resolutions: List of resolutions for test data
        data_root: Directory to download/store data
        temporal_subsample: Temporal subsampling rate
        spatial_subsample: Spatial subsampling rate
        return_processor: Whether to return the DataProcessor
        return_tuple_format: If True, convert dict outputs to (x, y) tuples
        
    Returns:
        train_loader: Training DataLoader
        test_loaders: Dict mapping resolution to test DataLoader
        data_processor: Optional DataProcessor for normalization
    """
    if not NEURALOP_AVAILABLE:
        raise ImportError("neuraloperator is required. Install with: pip install neuraloperator")
    
    if data_root is None:
        data_root = DEFAULT_DATA_ROOT / "burgers"
    data_root = Path(data_root)
    data_root.mkdir(parents=True, exist_ok=True)
    
    # First, try to load from local .pt files (generated by scripts/generate_burgers_data.py)
    train_file = data_root / f"burgers_train_{train_resolution}.pt"
    test_file = data_root / f"burgers_test_{train_resolution}.pt"
    
    if train_file.exists() and test_file.exists():
        train_data = torch.load(train_file)
        test_data = torch.load(test_file)
        
        # Create simple datasets
        class LocalBurgersDataset(Dataset):
            def __init__(self, data, n_samples=None):
                x = data['x'][:n_samples] if n_samples else data['x']
                y = data['y'][:n_samples] if n_samples else data['y']
                # Add channel dimension if needed
                if x.ndim == 2: x = x.unsqueeze(1)
                if y.ndim == 2: y = y.unsqueeze(1)
                self.x = x.float()
                self.y = y.float()
            def __len__(self): return len(self.x)
            def __getitem__(self, idx): return self.x[idx], self.y[idx]
        
        # --- Normalization Logic ---
        # We need to fit a normalizer if requested
        in_normalizer = None
        if encode_input:
             print("Computing stats for local Burgers input normalization...")
             # Use all training samples for stats
             all_x = train_data['x'].float()
             if all_x.ndim == 2: all_x = all_x.unsqueeze(1)
             in_normalizer = UnitGaussianNormalizer(all_x)
        
        train_db = LocalBurgersDataset(train_data, n_train)
        test_db = LocalBurgersDataset(test_data, n_test)
        
        if in_normalizer:
             class NormalizedDataset(Dataset):
                 def __init__(self, db, normalizer):
                     self.db = db
                     self.normalizer = normalizer
                 def __len__(self): return len(self.db)
                 def __getitem__(self, idx):
                     x, y = self.db[idx]
                     return self.normalizer(x).squeeze(0), y
             
             train_db = NormalizedDataset(train_db, in_normalizer)
             test_db = NormalizedDataset(test_db, in_normalizer)

        train_loader = DataLoader(train_db, batch_size=batch_size, shuffle=True, num_workers=0, pin_memory=True)
        test_loaders = {train_resolution: DataLoader(test_db, batch_size=test_batch_size, shuffle=False, num_workers=0, pin_memory=True)}
        
        # Create a dummy data processor to hold the normalizer
        processor = None
        if in_normalizer and DefaultDataProcessor:
             processor = DefaultDataProcessor(in_normalizer=in_normalizer)

        return train_loader, test_loaders, processor
    
    # Fall back to NeuralOperator's Burgers1dTimeDataset
    try:
        dataset = Burgers1dTimeDataset(
            root_dir=data_root,
            n_train=n_train,
            n_tests=[n_test] * len(test_resolutions),
            batch_size=batch_size,
            test_batch_sizes=[test_batch_size] * len(test_resolutions),
            train_resolution=train_resolution,
            test_resolutions=test_resolutions,
            temporal_subsample=temporal_subsample,
            spatial_subsample=spatial_subsample,
        )
    except FileNotFoundError as e:
        raise FileNotFoundError(
            f"Burgers data files not found at {data_root}. "
            f"NeuralOperator's Burgers1dTimeDataset does not auto-download. "
            f"Use the synthetic BurgersDataset from src.data.pde_datasets instead, or "
            f"manually generate burgers_train_{train_resolution}.pt and burgers_test_{{res}}.pt"
        ) from e
    
    # Wrap datasets if tuple format requested
    train_db = dataset.train_db
    if return_tuple_format:
        train_db = DictToTupleDataset(train_db)
    
    train_loader = DataLoader(
        train_db,
        batch_size=batch_size,
        shuffle=True,
        num_workers=0,
        pin_memory=True,
    )
    
    test_loaders = {}
    for res in test_resolutions:
        test_db = dataset.test_dbs[res]
        if return_tuple_format:
            test_db = DictToTupleDataset(test_db)
        test_loaders[res] = DataLoader(
            test_db,
            batch_size=test_batch_size,
            shuffle=False,
            num_workers=0,
            pin_memory=True,
        )
    
    if return_processor:
        return train_loader, test_loaders, dataset.data_processor
    return train_loader, test_loaders, None


